from tkinter import *

def display():
    print("This is a console message generated by clicking on a button! ")

def display1():
    print("This is another message")

root=Tk()
# root.geometry("1200x600")   #It is used for giving size of screen
root.resizable(True,True)  #It is used making size changable or not
root.title("First GUI Application")  #It is used for giving titles to the screen

# title1=Label(root,text="This is first text",font=("Arial",20,"bold"),padx=20,pady=20)
# title1.pack()
title2=Label(root,text="This is Sample Label",font=("Arial",20,"bold"),padx=20,pady=20)
title2.grid(row=1,column=0)
#Label is used to display text in screen
title3=Label(root,text="Another Message",font=("Cambria",20,"italic"),padx=10,pady=20)
title3.grid(row=1,column=1)

button1=Button(root,text="Display Message in console",font=("Arial",15,"bold"),command=display)
button1.grid(row=2,column=1)
#Button is used to create button on screen ,command is used to give functions of the button
button2=Button(root,text="Another Message in console",font=("Arial",15,"bold"),command=display1)
button2.grid(row=2,column=2)

root.mainloop()